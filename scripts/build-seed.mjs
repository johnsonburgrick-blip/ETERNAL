// Builds migrations/0002_seed.sql from scripts/seed-content.mjs and seed/images.json.
// Usage: node scripts/build-seed.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as C from './seed-content.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifestPath = path.join(root, 'seed/images.json');
const images = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, 'utf8')) : {};
const NOW = Date.parse('2026-11-10T09:00:00Z');
const DAY = 86400000;

const lit = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const out = ['-- Generated by scripts/build-seed.mjs. Initial content (safe to edit in the admin portal).', 'PRAGMA defer_foreign_keys = true;'];
const insert = (table, row) => {
  const cols = Object.keys(row);
  out.push(`INSERT INTO ${table} (${cols.join(', ')}) VALUES (${cols.map((c) => lit(row[c])).join(', ')});`);
};

// resolve image/commons references
const img = (v) => (typeof v === 'string' && v.startsWith('img:') ? images[v.slice(4)]?.url ?? '' : v);
const commons = (v) => (typeof v === 'string' && v.startsWith('commons:') ? images[v.slice(8)]?.source ?? '' : v);
const deep = (o) => (Array.isArray(o) ? o.map(deep) : o && typeof o === 'object' ? Object.fromEntries(Object.entries(o).map(([k, v]) => [k, deep(v)])) : img(o));

// ── media ──
for (const [slug, m] of Object.entries(images)) {
  insert('media_assets', {
    url: m.url, r2_key: null, kind: 'image', mime: 'image/jpeg', size: m.size, width: m.width, height: m.height,
    variants_json: JSON.stringify(m.variants), title: m.title, alt_json: JSON.stringify(m.alt ?? { en: '' }), category: m.category ?? 'history',
    credit: m.credit, license: m.license, source_url: m.source, created_at: NOW, updated_at: NOW,
  });
}

// ── settings ──
const settings = {
  siteName: 'Eternal Illuminati Covenant',
  contactEmail: 'support@yourdomain.com',
  enabledLocales: ['en', 'fr'],
  applicationsOpen: true,
  retentionDays: 730,
  consentVersion: '2026-11',
  defaultOgImage: images['hero-library']?.variants?.find((v) => v.w === 1600)?.url ?? images['hero-library']?.url ?? '/assets/og-default.jpg',
};
for (const [k, v] of Object.entries(settings)) insert('site_settings', { key: k, value: JSON.stringify(v), updated_at: NOW });

// ── pages & sections ──
let pageId = 0;
for (const p of C.pages) {
  pageId++;
  insert('pages', { id: pageId, slug: p.slug, name: p.name, meta_json: JSON.stringify(deep(p.meta)), status: 'published', in_sitemap: 1, sort: p.sort, created_at: NOW, updated_at: NOW, published_at: NOW });
  p.sections.forEach((s, i) => {
    const content = { shared: deep(s.shared ?? {}), en: deep(s.en ?? {}) };
    if (s.fr) content.fr = deep(s.fr);
    insert('page_sections', { page_id: pageId, uid: `seed-${p.slug}-${i}`, type: s.type, sort: i, visible: s.visible ? 1 : 0, settings_json: JSON.stringify(deep(s.settings ?? {})), content_json: JSON.stringify(content) });
  });
}

// ── navigation ──
let navId = 0;
const sortBy = {};
for (const n of C.nav) {
  navId++;
  const loc = n.location;
  sortBy[loc] = (sortBy[loc] ?? 0) + 10;
  insert('navigation_items', { id: navId, location: loc, parent_id: null, label_json: JSON.stringify(n.label), href: n.href, sort: sortBy[loc], visible: 1, is_button: n.isButton ? 1 : 0 });
  const parent = navId;
  (n.children ?? []).forEach((ch, i) => {
    navId++;
    insert('navigation_items', { id: navId, location: loc, parent_id: parent, label_json: JSON.stringify(ch.label), href: ch.href, sort: (i + 1) * 10, visible: 1, is_button: 0 });
  });
}

// ── collections ──
const base = (r) => ({ status: 'published', created_at: NOW, updated_at: NOW, i18n_json: JSON.stringify(r.i18n ?? {}) });
C.events.forEach((e) => insert('historical_events', { slug: e.slug, date_label: e.date_label, year: e.year, era: e.era, title: e.title, summary: e.summary, body: e.body, image: img(e.image), image_alt: e.image_alt, sources: e.sources, certainty: e.certainty, sort: e.sort, ...base(e) }));
C.figures.forEach((f, i) => insert('historical_figures', { slug: f.slug, name: f.name, role_title: f.role_title, dates_label: f.dates_label, portrait: img(f.portrait), portrait_alt: f.portrait_alt, summary: f.summary, background: f.background, body: f.body, sources: f.sources, sort: i, ...base(f) }));
C.principles.forEach((p) => insert('principles', { slug: p.slug, title: p.title, summary: p.summary, body: p.body, image: '', image_alt: '', sort: p.sort, ...base(p) }));
C.symbols.forEach((s) => insert('symbols', { slug: s.slug, name: s.name, image: img(s.image), image_alt: s.image_alt, origin: s.origin, summary: s.summary, body: s.body, sources: s.sources, sort: s.sort, ...base(s) }));
C.faqs.forEach((q) => insert('faqs', { slug: q.slug, question: q.question, answer: q.answer, category: q.category, sort: q.sort, ...base(q) }));
C.archives.forEach((a) => insert('historical_archives', {
  slug: a.slug, title: a.title, kind: a.kind, category: a.category, date_label: a.date_label, description: a.description, body: a.body, image: img(a.image ?? ''), image_alt: a.image_alt ?? '',
  file_url: '', external_url: commons(a.external_url ?? ''), downloadable: 0, license: a.license, source: a.source, sort: a.sort, ...base(a),
}));

C.categories.forEach((c, i) => insert('article_categories', { id: i + 1, slug: c.slug, name_json: JSON.stringify(c.name), sort: i }));
C.articles.forEach((a) => {
  const t = NOW - a.days_ago * DAY;
  insert('articles', {
    slug: a.slug, locale: 'en', title: a.title, excerpt: a.excerpt, body: a.body, cover_image: img(a.cover_image), cover_alt: a.cover_alt,
    category_id: C.categories.findIndex((c) => c.slug === a.category) + 1, tags: a.tags, author_name: 'Research Committee', status: 'published', publish_at: t,
    featured: a.featured ? 1 : 0, is_announcement: a.is_announcement ? 1 : 0, meta_title: '', meta_description: '', views: 0, created_at: t, updated_at: t, published_at: t,
  });
});

C.applicationFields.forEach((f) => insert('application_fields', {
  key: f.key, step: f.step, type: f.type, label_json: JSON.stringify(f.label), help_json: JSON.stringify(f.help), options_json: JSON.stringify(f.options),
  required: f.required, core: f.core, max_length: f.max_length, sort: f.sort, active: 1,
}));

fs.writeFileSync(path.join(root, 'migrations/0002_seed.sql'), out.join('\n') + '\n');
console.log(`wrote migrations/0002_seed.sql: ${out.length} statements, ${Object.keys(images).length} images`);
